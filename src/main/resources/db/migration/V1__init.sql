CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    email varchar(255) NOT NULL UNIQUE,
    role varchar(255) NOT NULL CHECK (role IN ('STUDENT', 'TEACHER', 'ADMIN'))
);

CREATE TABLE category (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE
);

CREATE TABLE tag (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE
);

CREATE TABLE profile (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL UNIQUE REFERENCES users (id),
    bio text,
    avatar_url varchar(2048)
);

CREATE TABLE course (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    description text NOT NULL,
    category_id integer NOT NULL REFERENCES category (id),
    teacher_id integer NOT NULL REFERENCES users (id),
    duration varchar(255) NOT NULL,
    start_date date NOT NULL
);

CREATE TABLE module (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id integer NOT NULL REFERENCES course (id) ON DELETE CASCADE,
    title varchar(255) NOT NULL,
    order_index integer NOT NULL,
    description text,
    UNIQUE (course_id, title)
);

CREATE TABLE lesson (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id integer NOT NULL REFERENCES module (id) ON DELETE CASCADE,
    title varchar(255) NOT NULL,
    content text,
    video_url varchar(2048),
    UNIQUE (module_id, title)
);

CREATE TABLE assignment (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id integer NOT NULL REFERENCES lesson (id) ON DELETE CASCADE,
    title varchar(255) NOT NULL,
    description text NOT NULL,
    due_date date NOT NULL,
    max_score integer NOT NULL CHECK (max_score > 0),
    UNIQUE (lesson_id, title)
);

CREATE TABLE submission (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id integer NOT NULL REFERENCES assignment (id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    submitted_at timestamp NOT NULL,
    content text NOT NULL,
    score integer CHECK (score >= 0),
    feedback text,
    UNIQUE (assignment_id, student_id)
);

CREATE TABLE course_tag (
    course_id integer NOT NULL REFERENCES course (id) ON DELETE CASCADE,
    tag_id integer NOT NULL REFERENCES tag (id),
    PRIMARY KEY (course_id, tag_id)
);

CREATE TABLE enrollment (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    course_id integer NOT NULL REFERENCES course (id) ON DELETE CASCADE,
    enroll_date date NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('ACTIVE', 'COMPLETED', 'CANCELLED')),
    UNIQUE (student_id, course_id)
);

CREATE TABLE course_review (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id integer NOT NULL REFERENCES course (id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment text NOT NULL,
    created_at timestamp NOT NULL
);

CREATE TABLE quiz (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id integer NOT NULL UNIQUE REFERENCES module (id) ON DELETE CASCADE,
    title varchar(255) NOT NULL,
    time_limit integer NOT NULL CHECK (time_limit > 0)
);

CREATE TABLE question (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id integer NOT NULL REFERENCES quiz (id) ON DELETE CASCADE,
    text text NOT NULL,
    type varchar(20) NOT NULL CHECK (type IN ('SINGLE_CHOICE', 'MULTIPLE_CHOICE'))
);

CREATE TABLE answer_option (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id integer NOT NULL REFERENCES question (id) ON DELETE CASCADE,
    text text NOT NULL,
    is_correct boolean NOT NULL
);

CREATE TABLE quiz_submission (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id integer NOT NULL REFERENCES quiz (id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    score integer NOT NULL CHECK (score BETWEEN 0 AND 100),
    taken_at timestamp NOT NULL
);
