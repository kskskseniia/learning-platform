CREATE TABLE course (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    description text NOT NULL,
    category_id integer NOT NULL,
    teacher_id integer NOT NULL,
    duration varchar(255) NOT NULL,
    start_date date NOT NULL,
    CONSTRAINT fk_course_category
        FOREIGN KEY (category_id) REFERENCES category (id),
    CONSTRAINT fk_course_teacher
        FOREIGN KEY (teacher_id) REFERENCES users (id)
);

CREATE TABLE course_tag (
    course_id integer NOT NULL,
    tag_id integer NOT NULL,
    PRIMARY KEY (course_id, tag_id),
    CONSTRAINT fk_course_tag_course
        FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_course_tag_tag
        FOREIGN KEY (tag_id) REFERENCES tag (id)
);

CREATE INDEX ix_course_category_id ON course (category_id);
CREATE INDEX ix_course_teacher_id ON course (teacher_id);
CREATE UNIQUE INDEX uk_course_title_teacher_start_date
    ON course (lower(title), teacher_id, start_date);
CREATE INDEX ix_course_tag_tag_id ON course_tag (tag_id);
