CREATE TABLE course_review (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id integer NOT NULL,
    student_id integer NOT NULL,
    rating integer NOT NULL,
    comment text NOT NULL,
    created_at timestamp NOT NULL,
    CONSTRAINT ck_course_review_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT fk_course_review_course
        FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_course_review_student
        FOREIGN KEY (student_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_course_review_course_id ON course_review (course_id);
CREATE INDEX ix_course_review_student_id ON course_review (student_id);
CREATE UNIQUE INDEX uk_course_review_student_course_comment_ci
    ON course_review (student_id, course_id, lower(btrim(comment)));
