CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    email varchar(255) NOT NULL UNIQUE,
    role varchar(255) NOT NULL CHECK (role IN ('STUDENT', 'TEACHER', 'ADMIN'))
);

CREATE TABLE IF NOT EXISTS category (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS tag (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS profile (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL UNIQUE,
    bio text,
    avatar_url varchar(2048),
    CONSTRAINT fk_profile_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_category_name ON category (name);
CREATE UNIQUE INDEX IF NOT EXISTS uk_category_name_ci ON category (lower(name));
CREATE UNIQUE INDEX IF NOT EXISTS uk_tag_name ON tag (name);
CREATE UNIQUE INDEX IF NOT EXISTS uk_tag_name_ci ON tag (lower(name));
